SUFFIX = ("股份有限公司", "有限责任公司", "有限公司", "集团", "股份", "公司")


def strip(name: str) -> str:
    out = name
    for suf in SUFFIX:
        if out.endswith(suf) and len(out) > len(suf) + 2:
            out = out[: -len(suf)]
    return out


def classify(name: str) -> tuple[str, str, str]:
    base = strip(name)
    for key, cat, mineral, reason in MAP:
        if key in base or key in name:
            return cat, mineral, reason
    return "P", "—", "未匹配规则，需人工判定"


def main() -> None:
    import openpyxl

    wb = openpyxl.load_workbook(XLSX, read_only=True)
    ws = wb["01_全量企业主表"]
    rows = list(ws.iter_rows(values_only=True))
    hdr = rows[0]
    idx = {h: i for i, h in enumerate(hdr)}
    wb.close()

    def g(row, col):
        v = row[idx[col]]
        return "" if v is None else str(v).strip()

    target = [r for r in rows[1:] if "矿产资源" in g(r, "二级环节")]
    out = []
    for r in target:
        cat, mineral, reason = classify(g(r, "企业名称"))
        out.append({
            "企业名称": g(r, "企业名称"),
            "一级环节": g(r, "一级环节"),
            "二级环节": g(r, "二级环节"),
            "分类": cat,
            "储能相关矿种/产品": mineral,
            "判定理由": reason,
            "行业地位": g(r, "行业地位"),
            "相关度": g(r, "相关度(归一)"),
            "是否上市": g(r, "是否上市公司"),
            "股票代码": g(r, "股票代码"),
            "省份": g(r, "属地(省)"),
            "建议动作": {
                "A": "保留 01-1，按近三年矿产品产量判定",
                "B": "保留 01-1，按近三年锂盐/化工品产量判定",
                "C": "移 01-2 电池主材与辅材",
                "D": "移 05/06/03/04 对应环节",
                "E": "移出上游（通用金属/石化/无关），按 4.6 判是否入链",
                "P": "待核实：先补产品与产出证据",
            }[cat],
        })

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(out[0].keys()))
        writer.writeheader()
        writer.writerows(out)

    counts = collections.Counter(row["分类"] for row in out)
    print("01-1 总行数", len(out))
    for cat in "ABCDEP":
        print(f"  {cat}: {counts.get(cat, 0)}")
    print("\nA 类（按矿产品产量判定）：")
    for row in out:
        if row["分类"] == "A":
            print("  ", row["企业名称"][:24], "|", row["储能相关矿种/产品"], "|", row["行业地位"])
    print("\nB 类（按加工产量判定）：")
    for row in out:
        if row["分类"] == "B":
            print("  ", row["企业名称"][:24], "|", row["储能相关矿种/产品"])
    print("\nCSV:", OUT)


if __name__ == "__main__":
    main()
