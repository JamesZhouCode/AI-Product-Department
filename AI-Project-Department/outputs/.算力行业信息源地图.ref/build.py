def make_sheet(wb, name, subtitle, headers, rows, widths, row_height=32, first=False):
    ws = wb.active if first else wb.create_sheet()
    ws.title = name
    ncol = len(headers)
    last_col = ws.cell(row=1, column=ncol).column_letter

    ws.merge_cells(f"A1:{last_col}1")
    t = ws["A1"]
    t.value = TITLE
    t.font = FONT_TITLE
    t.fill = FILL_TITLE
    t.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    ws.row_dimensions[1].height = 34

    ws.merge_cells(f"A2:{last_col}2")
    s = ws["A2"]
    s.value = subtitle
    s.font = FONT_SUB
    s.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    ws.row_dimensions[2].height = 22

    for i, h in enumerate(headers, start=1):
        c = ws.cell(row=3, column=i, value=h)
        c.font = FONT_HEAD
        c.fill = FILL_HEAD
        c.alignment = ALIGN_C
        c.border = BORDER
    ws.row_dimensions[3].height = 26

    for idx, row in enumerate(rows, start=1):
        r = idx + 3
        for col, val in enumerate(row, start=1):
            c = ws.cell(row=r, column=col, value=val)
            c.font = FONT_BASE
            c.border = BORDER
            c.alignment = ALIGN_C if col == 1 else ALIGN_WRAP
            if idx % 2 == 0:
                c.fill = FILL_SOFT
        ws.row_dimensions[r].height = row_height

    for col, w in zip("ABCDEFGHIJ", widths):
        ws.column_dimensions[col].width = w
    ws.freeze_panes = "A4"
    ws.auto_filter.ref = f"A3:{last_col}{len(rows) + 3}"
    return ws


