    for _ in range(4):
        nxt = MERGE.get(cur)
        if nxt is None:
            low = cur.lower()
            for a, b in MERGE.items():
                if a.lower() == low:
                    nxt = b
                    break
        if not nxt or nxt == cur:
            return cur
        cur = nxt
    return cur
